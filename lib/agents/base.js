// The codified Solid-vs-Advise predicate (G-1661, plan 21-06). Pure function
// of a module's three declared capability fields — see the contract
// doc-comment above. Never reads the module's own `tier` field: a predicate
// that consults the answer it is checking is vacuous.
function computeExpectedTier(capabilities) {
  if (!capabilities || typeof capabilities !== 'object') {
    throw new TypeError(
      'computeExpectedTier: expected an object with installsEnforcedHooks, ' +
      'writesIgnoreFile, ignoreFileHonored'
    );
  }

  // Stage 1 — presence. No default for any field: a module that never
  // declared its capabilities must not silently satisfy whatever tier it
  // happens to state.
  const REQUIRED_FIELDS = ['installsEnforcedHooks', 'writesIgnoreFile', 'ignoreFileHonored'];
  for (const field of REQUIRED_FIELDS) {
    if (!Object.prototype.hasOwnProperty.call(capabilities, field)) {
      throw new TypeError(`computeExpectedTier: missing required capability field "${field}"`);
    }
  }

  const { installsEnforcedHooks, writesIgnoreFile, ignoreFileHonored } = capabilities;

  // Stage 2 — type.
  if (typeof installsEnforcedHooks !== 'boolean') {
    throw new TypeError(
      `computeExpectedTier: "installsEnforcedHooks" must be a boolean, got ${typeof installsEnforcedHooks}`
    );
  }
  if (typeof writesIgnoreFile !== 'boolean') {
    throw new TypeError(
      `computeExpectedTier: "writesIgnoreFile" must be a boolean, got ${typeof writesIgnoreFile}`
    );
  }
  if (ignoreFileHonored !== null && typeof ignoreFileHonored !== 'boolean') {
    throw new TypeError(
      `computeExpectedTier: "ignoreFileHonored" must be a boolean or null, got ${typeof ignoreFileHonored}`
    );
  }

  // Stage 3 — relational coherence. The three fields are not independent; a
  // contradictory combination throws naming both offending fields rather
  // than silently resolving to tier 3 (the worst possible outcome — an
  // internally-inconsistent declaration would present as a correctly-graded
  // Advise agent).
  if (writesIgnoreFile === false && ignoreFileHonored !== null) {
    throw new TypeError(
      'computeExpectedTier: contradictory capability declaration — ' +
      `"writesIgnoreFile" is false but "ignoreFileHonored" is ${JSON.stringify(ignoreFileHonored)}; ` +
      'a module that writes no ignore file cannot carry a verdict about one being honored ' +
      '("writesIgnoreFile": false requires "ignoreFileHonored" === null)'
    );
  }
  if (writesIgnoreFile === true && ignoreFileHonored === null) {
    throw new TypeError(
      'computeExpectedTier: contradictory capability declaration — ' +
      '"writesIgnoreFile" is true but "ignoreFileHonored" is null; an honored-ness verdict ' +
      'is required once a file is written ("ignoreFileHonored" !== null requires ' +
      '"writesIgnoreFile" === true)'
    );
  }

  // Stage 4 — resolution, over the six coherent states only. Hook
  // installation is checked first and dominates: a module that both
  // installs hooks and writes an honored ignore file is unambiguously tier
  // 1. Strict equality against `true` for the honored flag so a truthy
  // non-boolean can never reach the tier-2 branch (unreachable in practice
  // after stage 2, kept as defense in depth).
  if (installsEnforcedHooks) return 1;
  if (writesIgnoreFile && ignoreFileHonored === true) return 2;
  return 3;
}

module.exports = {
  commandExists,
  getVersion,
  macAppExists,
  vscodeExtensionExists,
  writeIgnoreFile,
  SENSITIVE_PATTERNS,
  computeExpectedTier,
};
